CREATE SEQUENCE SEQ_EQUIPE_MANUTENCAO       START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TRECHO_RODOVIA          START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INTERVENCAO_OPERACIONAL START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_RELATORIO_PRIORIDADE    START WITH 1 INCREMENT BY 1 NOCACHE;

-- Equipes de manutenção
CREATE TABLE EQUIPE_MANUTENCAO (
    ID            NUMBER         PRIMARY KEY,
    NOME_EQUIPE   VARCHAR2(100)  NOT NULL,
    RESPONSAVEL   VARCHAR2(100)  NOT NULL
);

-- Trechos de rodovia (MONITORADO_IOT é o discriminador da herança JPA)
CREATE TABLE TRECHO_RODOVIA (
    ID                NUMBER         PRIMARY KEY,
    NOME_RODOVIA      VARCHAR2(50)   NOT NULL,
    KM_INICIAL        NUMBER(10,2)   NOT NULL,
    KM_FINAL          NUMBER(10,2)   NOT NULL,
    NIVEL_VEGETACAO   NUMBER(10,2)   NOT NULL,
    TIPO_TERRENO      VARCHAR2(20)   NOT NULL,
    MONITORADO_IOT    NUMBER(1)      DEFAULT 0 NOT NULL,
    CONSTRAINT CK_MONITORADO_IOT CHECK (MONITORADO_IOT IN (0, 1))
);

-- Intervenções (TIPO_INTERVENCAO é o discriminador da herança JPA)
CREATE TABLE INTERVENCAO_OPERACIONAL (
    ID                 NUMBER         PRIMARY KEY,
    ID_TRECHO          NUMBER         NOT NULL,
    ID_EQUIPE          NUMBER         NOT NULL,
    TIPO_INTERVENCAO   VARCHAR2(50)   NOT NULL,
    URGENTE            NUMBER(1)      DEFAULT 0 NOT NULL,
    DATA_EXECUCAO      TIMESTAMP      NOT NULL,
    OBSERVACAO         VARCHAR2(200),
    CONSTRAINT FK_INTERVENCAO_TRECHO
        FOREIGN KEY (ID_TRECHO) REFERENCES TRECHO_RODOVIA (ID),
    CONSTRAINT FK_INTERVENCAO_EQUIPE
        FOREIGN KEY (ID_EQUIPE) REFERENCES EQUIPE_MANUTENCAO (ID),
    CONSTRAINT CK_TIPO_INTERVENCAO
        CHECK (TIPO_INTERVENCAO IN ('SEM_INTERVENCAO', 'PULVERIZACAO', 'ROCADA_MECANIZADA'))
);

-- Histórico dos relatórios de priorização
CREATE TABLE RELATORIO_PRIORIDADE (
    ID              NUMBER         PRIMARY KEY,
    DATA_GERACAO    TIMESTAMP      NOT NULL,
    QT_URGENTE      NUMBER(5)      DEFAULT 0 NOT NULL,
    QT_CRITICO      NUMBER(5)      DEFAULT 0 NOT NULL,
    QT_ATENCAO      NUMBER(5)      DEFAULT 0 NOT NULL,
    QT_NORMAL       NUMBER(5)      DEFAULT 0 NOT NULL,
    RESUMO          VARCHAR2(500)
);
